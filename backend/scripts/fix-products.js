async function main() {
  const pool = mysql.createPool(DB).promise();
  let fixed = 0;
  let inserted = 0;
  let skipped = 0;

  for (const [slug, features] of Object.entries(corrections)) {
    const [res] = await pool.execute('UPDATE products SET features = ? WHERE slug = ?', [
      JSON.stringify(features),
      slug,
    ]);
    fixed += res.affectedRows;
  }

  for (const p of newProducts) {
    const [rows] = await pool.execute('SELECT id FROM products WHERE slug = ?', [p.slug]);
    if (rows.length) {
      skipped += 1;
      continue;
    }
    await pool.execute(
      'INSERT INTO products (category_id, name, slug, description, price, quantity, image, features, featured, status) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
      [
        p.category_id,
        p.name,
        p.slug,
        p.description,
        p.price,
        p.quantity,
        p.image,
        JSON.stringify(p.features),
        p.featured,
        'active',
      ]
    );
    inserted += 1;
  }

  console.log(`Features corrected: ${fixed}`);
  console.log(`New products inserted: ${inserted}`);
  console.log(`New products skipped (already exist): ${skipped}`);

  const [counts] = await pool.execute(
    'SELECT c.name, COUNT(p.id) AS total FROM categories c LEFT JOIN products p ON p.category_id = c.id GROUP BY c.id, c.name ORDER BY c.id'
  );
  console.log('\nProducts per category:');
  for (const r of counts) console.log(`  ${r.name}: ${r.total}`);

  await pool.end();
  process.exit(0);
}

if (require.main === module) {
  main().catch((e) => {
    console.error('ERROR:', e.message);
    process.exit(1);
  });
}

module.exports = { corrections, newProducts };
